type PaletteDraft = {
  id: string;
  name: string;
  tagline: string;
  category: ThemePaletteCategory;
  bg: string;
  bgDeep: string;
  ink: string;
  muted: string;
  brand: string;
  brandStrong: string;
  fire: string;
  fireStrong: string;
  /** "r, g, b" 用于 soft / line / shadow */
  inkRgb: string;
  brandRgb: string;
  fireRgb: string;
  card?: string;
  lineAlpha?: number;
  brandSoftAlpha?: number;
  fireSoftAlpha?: number;
  shadowAlpha?: number;
};

/** 统一拼装 tokens，保证每套配色字段形状一致、对比度可控 */
function createPalette(draft: PaletteDraft): ThemePalette {
  const lineAlpha = draft.lineAlpha ?? 0.12;
  const brandSoftAlpha = draft.brandSoftAlpha ?? 0.12;
  const fireSoftAlpha = draft.fireSoftAlpha ?? 0.12;
  const shadowAlpha = draft.shadowAlpha ?? 0.07;
  const card = draft.card ?? "rgba(255, 255, 255, 0.94)";

  return {
    id: draft.id,
    name: draft.name,
    tagline: draft.tagline,
    category: draft.category,
    tokens: {
      bg: draft.bg,
      bgDeep: draft.bgDeep,
      ink: draft.ink,
      muted: draft.muted,
      line: `rgba(${draft.inkRgb}, ${lineAlpha})`,
      brand: draft.brand,
      brandStrong: draft.brandStrong,
      brandSoft: `rgba(${draft.brandRgb}, ${brandSoftAlpha})`,
      fire: draft.fire,
      fireStrong: draft.fireStrong,
      fireSoft: `rgba(${draft.fireRgb}, ${fireSoftAlpha})`,
      card,
      shadow: `0 16px 40px rgba(${draft.inkRgb}, ${shadowAlpha})`,
    },
    swatches: [draft.bg, draft.brand, draft.brandStrong, draft.fire],
  };
}

